// Строки версии 1.1 — по файлу на направление (так параллельная работа не задевает один файл)
/** Весь словарь [ru, kk, en] — экспортируется для проверки полноты в i18n.test.ts */
export const STRINGS: Readonly<Record<string, readonly [string, string, string]>> = { ...BASE, ...S_SPEED, ...S_FLOW, ...S_RITE, ...S_TODAY, ...S_JOURNEY }
const S = STRINGS

const IDX: Record<Lang, 0 | 1 | 2> = { ru: 0, kk: 1, en: 2 }

/** Строка интерфейса на текущем языке (нет перевода — русский; нет ключа — сам ключ) */
export function t(key: string): string {
  const r = S[key]
  if (!r) return key
  return r[IDX[lang.value]] || r[0]
}

/** Строка с подстановками: tf('pack.got', { n: 3, m: 10 }) — «Отмечено 3 из 10» */
export function tf(key: string, vars: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

/* Язык документа следует выбранному: озвучка, переносы, экранные чтецы */
effect(() => { if (typeof document !== 'undefined') document.documentElement.lang = lang.value })

/** Программа группы всегда на русском: lang="ru" для её текста, когда интерфейс на другом языке */
export function progLang(): 'ru' | undefined {
  return lang.value === 'ru' ? undefined : 'ru'
}

/** Выбор перевода из объекта вида { ru, kk, en } (имена зикров, подписи погоды) */
export function pick(o: Record<string, string | undefined> | undefined, fallback = ''): string {
  if (!o) return fallback
  return o[lang.value] || o.ru || fallback
}

/** Дата ДД.ММ (ru/kk) или DD Mon (en) */
export function fmtDate(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number)
  if (!y || !m || !d) return iso
  if (lang.value === 'en') return `${d} ${['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'][m - 1]}`
  return `${String(d).padStart(2, '0')}.${String(m).padStart(2, '0')}`
}
